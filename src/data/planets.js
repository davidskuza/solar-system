/**
 * Computes the world-space position of a celestial body at simulation time `t`.
 */
export function computeOrbitPosition(body, t, parentPos = null) {
  if (!body.orbitRadius) {
    return [0, 0, 0];
  }
  const angle = body.initialAngle + t * body.orbitSpeed;
  const a = body.orbitRadius;
  const e = body.eccentricity || 0;
  const b = a * Math.sqrt(1 - e * e);
  const c = a * e; // focus offset so Sun sits at focus

  const localX = Math.cos(angle) * a - c;
  const localZ = Math.sin(angle) * b;

  const incRad = ((body.inclinationDeg || 0) * Math.PI) / 180;
  const x = localX;
  const y = localZ * Math.sin(incRad);
  const z = localZ * Math.cos(incRad);

  if (parentPos) {
    return [parentPos[0] + x, parentPos[1] + y, parentPos[2] + z];
  }
  return [x, y, z];
}
